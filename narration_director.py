"""Local narration timeline nodes for AUDIO produced by external TTS nodes."""
import json
import math

import torch
import torch.nn.functional as F

from comfy_api.latest import io

from .audio_nodes import _audio, _parts


NarrationCueType = io.Custom("NARRATION_CUE")
_MATCH_MODES = ["natural", "trim", "fit"]
_MAX_DURATION_SECONDS = 36000.0
_MAX_CUES = 1000


def _resample(waveform, source_rate, target_rate):
    if source_rate == target_rate:
        return waveform
    length = round(waveform.shape[-1] * target_rate / source_rate)
    return F.interpolate(waveform, size=length, mode="linear", align_corners=False)


def _mono(waveform):
    if waveform.ndim != 3 or waveform.shape[0] != 1:
        raise ValueError("Narration Director supports one audio batch at a time")
    if waveform.shape[1] == 0:
        raise ValueError("Narration audio must contain at least one channel")
    return waveform.mean(dim=1, keepdim=True) if waveform.shape[1] > 1 else waveform


def _validate_time(value, name):
    value = float(value)
    if not math.isfinite(value) or value < 0 or value > _MAX_DURATION_SECONDS:
        raise ValueError(f"{name} must be between 0 and {_MAX_DURATION_SECONDS:g} seconds")
    return value


def _validate_volume(value, name, maximum):
    value = float(value)
    if not math.isfinite(value) or value < 0 or value > maximum:
        raise ValueError(f"{name} must be between 0 and {maximum:g}")
    return value


def _timeline_overrides(timeline_data):
    if not timeline_data.strip():
        return {}
    try:
        data = json.loads(timeline_data)
    except json.JSONDecodeError as error:
        raise ValueError(f"Invalid narration timeline JSON: {error.msg}") from error
    segments = data.get("segments", [])
    if not isinstance(segments, list) or len(segments) > _MAX_CUES:
        raise ValueError(f"Narration timeline supports at most {_MAX_CUES} segments")
    return {str(segment.get("id")): segment for segment in segments if isinstance(segment, dict) and segment.get("id") is not None}


class NarrationCue(io.ComfyNode):
    """Attach timeline metadata to AUDIO generated by an external local TTS node such as IndexTTS2."""

    @classmethod
    def define_schema(cls):
        return io.Schema(
            node_id="VideoSplitNarrationCue",
            display_name="Narration Cue",
            category="video/audio",
            description="Place AUDIO from a local TTS node on the narration timeline.",
            inputs=[
                io.Audio.Input("audio", tooltip="Connect the AUDIO output of an IndexTTS2 node"),
                io.String.Input("text", default="", multiline=True, tooltip="Script text used as the timeline label"),
                io.Float.Input("start_time", default=0.0, min=0.0, max=_MAX_DURATION_SECONDS, step=0.01),
                io.Float.Input("end_time", default=5.0, min=0.0, max=_MAX_DURATION_SECONDS, step=0.01,
                               tooltip="Reserved timeline end; natural mode may finish earlier"),
                io.Float.Input("volume", default=1.0, min=0.0, max=5.0, step=0.05),
                io.String.Input("cue_id", default="", tooltip="Optional stable ID used by Narration Director overrides"),
            ],
            outputs=[NarrationCueType.Output(display_name="cue")],
        )

    @classmethod
    def execute(cls, audio, text, start_time, end_time, volume, cue_id):
        start_time = _validate_time(start_time, "start_time")
        end_time = _validate_time(end_time, "end_time")
        if end_time <= start_time:
            raise ValueError("end_time must be greater than start_time")
        waveform, sample_rate = _parts(audio)
        _mono(waveform)
        return io.NodeOutput({
            "id": cue_id.strip(),
            "audio": audio,
            "text": text,
            "start": start_time,
            "end": end_time,
            "volume": _validate_volume(volume, "volume", 5.0),
            "sample_rate": sample_rate,
            "duration": waveform.shape[-1] / sample_rate,
        })


class NarrationDirector(io.ComfyNode):
    """Compose any number of local TTS AUDIO cues on a frame-aligned timeline."""

    @classmethod
    def define_schema(cls):
        cues = io.Autogrow.TemplatePrefix(
            input=NarrationCueType.Input("cue", optional=True),
            prefix="cue_",
            min=0,
        )
        return io.Schema(
            node_id="VideoSplitNarrationDirector",
            display_name="Narration Director",
            category="video/audio",
            description="Arrange AUDIO from external local TTS nodes on a visual timeline. No model loading or network requests.",
            inputs=[
                io.Int.Input("total_frames", default=1440, min=1, max=864000),
                io.Float.Input("fps", default=24.0, min=1.0, max=240.0, step=0.01),
                io.Int.Input("sample_rate", default=44100, min=8000, max=192000),
                io.Combo.Input("match_mode", options=_MATCH_MODES, default="natural",
                               tooltip="natural keeps speech length; trim cuts at cue end; fit resamples to fill the cue"),
                io.Autogrow.Input("cues", template=cues, optional=True),
                io.Audio.Input("background_audio", optional=True),
                io.Float.Input("background_volume", default=0.3, min=0.0, max=2.0, step=0.05),
                io.String.Input("timeline_data", default="", multiline=True,
                                tooltip="Visual editor state; cue IDs may override start/end/text/volume"),
            ],
            outputs=[
                io.Audio.Output(display_name="audio"),
                io.Float.Output(display_name="duration"),
                io.String.Output(display_name="timeline_json"),
            ],
        )

    @classmethod
    def execute(cls, total_frames, fps, sample_rate, match_mode, cues=None, background_audio=None,
                background_volume=0.3, timeline_data=""):
        duration = total_frames / fps
        if duration > _MAX_DURATION_SECONDS:
            raise ValueError(f"Narration duration must not exceed {_MAX_DURATION_SECONDS:g} seconds")
        if match_mode not in _MATCH_MODES:
            raise ValueError(f"Unsupported narration match mode: {match_mode}")

        cue_values = [] if cues is None else [value for value in cues.values() if value is not None]
        if len(cue_values) > _MAX_CUES:
            raise ValueError(f"Narration Director supports at most {_MAX_CUES} cues")
        overrides = _timeline_overrides(timeline_data)

        reference = None
        if cue_values:
            reference, _ = _parts(cue_values[0]["audio"])
        elif background_audio is not None:
            reference, _ = _parts(background_audio)
        device = reference.device if reference is not None else torch.device("cpu")
        dtype = reference.dtype if reference is not None else torch.float32
        total_samples = round(total_frames * sample_rate / fps)
        result = torch.zeros((1, 1, total_samples), device=device, dtype=dtype)
        timeline_segments = []

        for index, cue in enumerate(cue_values):
            cue_id = cue.get("id") or f"cue_{index + 1}"
            override = overrides.get(cue_id, {})
            start = _validate_time(override.get("start", cue["start"]), "cue start")
            end = _validate_time(override.get("end", cue["end"]), "cue end")
            if start >= duration:
                continue
            if end <= start:
                raise ValueError(f"Cue '{cue_id}' end must be greater than its start")

            waveform, rate = _parts(cue["audio"])
            waveform = _mono(waveform).to(device=device, dtype=dtype)
            waveform = _resample(waveform, rate, sample_rate)
            available = max(0, round((min(end, duration) - start) * sample_rate))
            if match_mode == "fit" and available:
                waveform = F.interpolate(waveform, size=available, mode="linear", align_corners=False)
            elif match_mode == "trim":
                waveform = waveform[..., :available]

            start_sample = round(start * sample_rate)
            length = min(waveform.shape[-1], total_samples - start_sample)
            if length > 0:
                volume = _validate_volume(override.get("volume", cue.get("volume", 1.0)), "cue volume", 5.0)
                result[..., start_sample:start_sample + length] += waveform[..., :length] * volume
            timeline_segments.append({
                "id": cue_id,
                "start": start,
                "end": end,
                "text": str(override.get("text", cue.get("text", ""))),
                "duration": waveform.shape[-1] / sample_rate,
                "volume": _validate_volume(override.get("volume", cue.get("volume", 1.0)), "cue volume", 5.0),
            })

        if background_audio is not None:
            background, rate = _parts(background_audio)
            background = _mono(background).to(device=device, dtype=dtype)
            background = _resample(background, rate, sample_rate)
            if background.shape[-1] > 0:
                if background.shape[-1] < total_samples:
                    background = background.repeat(1, 1, total_samples // background.shape[-1] + 1)
                background_volume = _validate_volume(background_volume, "background_volume", 2.0)
                result += background[..., :total_samples] * background_volume

        timeline_json = json.dumps({
            "total_frames": total_frames,
            "fps": fps,
            "sample_rate": sample_rate,
            "segments": timeline_segments,
        }, ensure_ascii=False)
        return io.NodeOutput(_audio(result.clamp(-1, 1), sample_rate), duration, timeline_json)


